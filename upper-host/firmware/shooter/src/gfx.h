static inline void gx_pixel(uint8_t *p,int x,int y,int c){if((unsigned)x<GAME_W&&(unsigned)y<GAME_H)p[y*GAME_W+x]=(uint8_t)c;}
static inline void gx_rect(uint8_t *p,int x,int y,int w,int h,int c){
 int right=x+w,bottom=y+h;if(x<0)x=0;if(y<0)y=0;if(right>GAME_W)right=GAME_W;if(bottom>GAME_H)bottom=GAME_H;
 for(int yy=y;yy<bottom;yy++){uint8_t *row=p+yy*GAME_W;for(int xx=x;xx<right;xx++)row[xx]=(uint8_t)c;}
}
static inline void gx_outline(uint8_t *p,int x,int y,int w,int h,int c){gx_rect(p,x,y,w,1,c);gx_rect(p,x,y+h-1,w,1,c);gx_rect(p,x,y,1,h,c);gx_rect(p,x+w-1,y,1,h,c);}
static inline void gx_panel(uint8_t *p,int x,int y,int w,int h,int fill,int edge){
 gx_rect(p,x+2,y+3,w,h,0);gx_rect(p,x,y,w,h,fill);gx_outline(p,x,y,w,h,edge);
 gx_pixel(p,x,y,0);gx_pixel(p,x+w-1,y,0);gx_pixel(p,x,y+h-1,0);gx_pixel(p,x+w-1,y+h-1,0);
}
static inline void gx_text(uint8_t *p,int x,int y,const char *s,int c,int scale){
 for(;*s;s++,x+=6*scale){const uint8_t *v=0;uint8_t special[5]={0};
  if(*s>='A'&&*s<='Z')v=gx_font[*s-'A'];else if(*s>='0'&&*s<='9')v=gx_font[26+*s-'0'];
  else{switch(*s){case '-':for(int i=0;i<5;i++)special[i]=8;break;
   case '+':special[0]=special[1]=special[3]=special[4]=8;special[2]=0x3e;break;
   case '/':special[0]=0x60;special[1]=0x18;special[2]=6;special[3]=1;break;
   case ':':special[2]=0x24;break;case '.':special[2]=0x40;break;
   case '>':special[1]=0x41;special[2]=0x22;special[3]=0x14;special[4]=8;break;default:break;}v=special;}
  for(int xx=0;xx<5;xx++)for(int yy=0;yy<7;yy++)if(v[xx]&(1u<<yy))gx_rect(p,x+xx*scale,y+yy*scale,scale,scale,c);
 }
}
static inline void gx_number(uint8_t *p,int x,int y,uint32_t n,int count,int c,int scale){
 char s[11];if(count>10)count=10;s[count]=0;for(int i=count-1;i>=0;i--){s[i]=(char)('0'+n%10);n/=10;}gx_text(p,x,y,s,c,scale);
}
static inline void gx_tile(uint8_t *p,int x,int y,int w,int h,int color){
 gx_rect(p,x,y,w,h,0);gx_rect(p,x+1,y+1,w-2,h-2,color);gx_rect(p,x+2,y+1,w-4,1,6);
 gx_rect(p,x+1,y+2,1,h-4,23);gx_rect(p,x+2,y+h-2,w-3,1,3);gx_pixel(p,x+w-2,y+1,18);
}
static inline void gx_key(uint8_t *p,int x,int y,const char *s,int color){gx_panel(p,x,y,17,12,2,3);gx_text(p,x+3,y+2,s,color,1);}
